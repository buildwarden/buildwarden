package queue

import (
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"slices"
	"strings"
)

// DigestDir holds the runs' digests: each run writes its own file,
// digest/<date>/<UTC start>-<worker>.md, and the day's page digest/<date>.md
// is built from them (FLOW-13, LOOP-06).
const DigestDir = "digest"

// digestMark opens a page wf digest built. A page without it was written by
// hand, before the runs had files of their own.
const digestMark = "<!-- Generated by wf digest"

// earlierPage is the name a hand-written day's page is moved to in its
// directory: it sorts before every run's file.
const earlierPage = "00000000T000000Z-earlier-page.md"

var dayRe = regexp.MustCompile(`^\d{4}-\d{2}-\d{2}$`)

// Digest builds the day's page of every day that has a directory of run
// files, and returns the paths it wrote, from the state's root. A page
// written by hand before the day's directory existed is first moved into the
// directory as its first file, once, so nothing is overwritten.
func (s *State) Digest() ([]string, error) {
	entries, err := os.ReadDir(filepath.Join(s.Dir, DigestDir))
	if errors.Is(err, os.ErrNotExist) {
		return nil, nil
	}
	if err != nil {
		return nil, err
	}
	var out []string
	for _, e := range entries {
		if !e.IsDir() || !dayRe.MatchString(e.Name()) {
			continue
		}
		paths, err := s.digestDay(e.Name())
		if err != nil {
			return nil, err
		}
		out = append(out, paths...)
	}
	return out, nil
}

func (s *State) digestDay(day string) ([]string, error) {
	page := filepath.Join(DigestDir, day+".md")
	dir := filepath.Join(DigestDir, day)
	var out []string
	old, err := os.ReadFile(filepath.Join(s.Dir, page))
	switch {
	case errors.Is(err, os.ErrNotExist):
	case err != nil:
		return nil, err
	case !strings.HasPrefix(string(old), digestMark):
		moved := filepath.Join(dir, earlierPage)
		if _, err := os.Stat(filepath.Join(s.Dir, moved)); err == nil {
			return nil, fmt.Errorf("%s was written by hand, and %s already exists: "+
				"move its text into a run's file by hand", page, moved)
		}
		if err := os.WriteFile(filepath.Join(s.Dir, moved), old, 0o644); err != nil {
			return nil, err
		}
		out = append(out, moved)
	}
	text, err := DigestPage(filepath.Join(s.Dir, dir), day)
	if err != nil {
		return nil, err
	}
	if err := os.WriteFile(filepath.Join(s.Dir, page), []byte(text), 0o644); err != nil {
		return nil, err
	}
	return append(out, page), nil
}

// DigestPage is the day's page: the files of the day's directory, in file
// name order, under the line that says it is generated. The same files give
// the same page.
func DigestPage(dir, day string) (string, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return "", err
	}
	var names []string
	for _, e := range entries {
		if !e.IsDir() && strings.HasSuffix(e.Name(), ".md") {
			names = append(names, e.Name())
		}
	}
	slices.Sort(names)
	var b strings.Builder
	fmt.Fprintf(&b, "%s from %s/%s/; do not edit. -->\n\n# Digest %s\n", digestMark,
		DigestDir, day, day)
	for _, n := range names {
		text, err := os.ReadFile(filepath.Join(dir, n))
		if err != nil {
			return "", err
		}
		fmt.Fprintf(&b, "\n%s\n", strings.TrimRight(string(text), "\n"))
	}
	return b.String(), nil
}
