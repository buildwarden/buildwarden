package queue

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"time"
)

// SummaryFile is the generated overview at the root of the workflow branch.
const SummaryFile = "QUEUE.md"

// recentDays is how far back "Recently done" reaches from the updated time.
const recentDays = 7

// Summary renders the queue as Markdown: what needs the human first, then
// what is active, what waits on a host, the backlog and what finished
// recently. It reads only the state, never the clock, so the same state always
// renders the same text.
func Summary(s *State) string {
	updated := s.updated()
	var b strings.Builder
	fmt.Fprintf(&b, "# Queue\n\nGenerated by `wf` from `queue/*.yaml`; do not edit. "+
		"Updated %s.\n", stamp(updated))

	section(&b, "Needs Jeff", s.needsHuman(), "Nothing.")
	s.writeActive(&b)
	if hosts := s.hostSteps(); len(hosts) > 0 {
		section(&b, "Waiting on a host", hosts, "")
	}
	s.writeBacklog(&b)
	section(&b, "Recently done", s.recentlyDone(updated), "Nothing in the last 7 days.")
	return b.String()
}

// WriteSummary writes Summary to QUEUE.md in the state's directory.
func (s *State) WriteSummary() error {
	return os.WriteFile(filepath.Join(s.Dir, SummaryFile), []byte(Summary(s)), 0o644)
}

func section(b *strings.Builder, title string, lines []string, empty string) {
	fmt.Fprintf(b, "\n## %s\n\n", title)
	if len(lines) == 0 {
		fmt.Fprintf(b, "%s\n", empty)
		return
	}
	for _, l := range lines {
		fmt.Fprintf(b, "- %s\n", l)
	}
}

// updated is the newest history event across the queue.
func (s *State) updated() time.Time {
	var t time.Time
	for _, f := range s.Features {
		for _, e := range f.History {
			if e.At.After(t) {
				t = e.At
			}
		}
	}
	return t
}

func stamp(t time.Time) string {
	if t.IsZero() {
		return "never"
	}
	return t.UTC().Format("2006-01-02 15:04 UTC")
}

// readySteps returns the feature's pending steps whose needs are all done.
func readySteps(f *Feature) []*Step {
	done := map[string]bool{}
	for _, st := range f.Steps {
		if st.Status == "done" {
			done[st.ID] = true
		}
	}
	var out []*Step
	for i := range f.Steps {
		st := &f.Steps[i]
		if st.Status == "pending" && allDone(st.Needs, done) {
			out = append(out, st)
		}
	}
	return out
}

// waitsOnMerge reports whether the item's PR waits for the human's merge.
func waitsOnMerge(f *Feature) bool {
	return f.Status == "in_progress" && ((f.Round == "feature" && f.Phase == 7) ||
		(f.Round == "process" && f.Phase == 3))
}

func prRef(f *Feature) string {
	if f.PR == nil || f.PR.Number == 0 {
		return "no PR recorded"
	}
	return fmt.Sprintf("PR #%d", f.PR.Number)
}

func (s *State) needsHuman() []string {
	var out []string
	for _, f := range s.Features {
		if f.Status == "done" {
			continue
		}
		add := func(format string, a ...any) {
			out = append(out, "**"+f.Feature+"**: "+fmt.Sprintf(format, a...))
		}
		for _, q := range f.OpenBlocking() {
			add("blocking question %s: %s (recommended: %s)", q.ID, q.Question,
				q.Recommended)
		}
		for _, st := range readySteps(f) {
			if st.Affinity == "human" && !strings.Contains(st.ID, "-answer-") {
				add("%s", humanStep(st))
			}
		}
		if waitsOnMerge(f) {
			add("%s waiting for your merge", prRef(f))
		}
		if s.Runaway(f) {
			b := f.Budget
			add("runaway budget, %d of %d estimated steps spent (FLOW-13)",
				b.Spent.Steps, b.Estimate.Steps)
		}
	}
	return out
}

func humanStep(st *Step) string {
	switch {
	case strings.Contains(st.ID, "design-review"), strings.HasSuffix(st.ID, "1-design"):
		return "design review (`" + st.ID + "`, FLOW-19)"
	case strings.Contains(st.ID, "escalate"):
		return "escalation (`" + st.ID + "`)"
	}
	return "`" + st.ID + "`"
}

func (s *State) writeActive(b *strings.Builder) {
	fmt.Fprintf(b, "\n## Active\n\n")
	var rows []string
	for _, f := range s.Features {
		if f.Status != "in_progress" {
			continue
		}
		var next []string
		for _, st := range readySteps(f) {
			n := fmt.Sprintf("%s (%s", st.ID, st.Affinity)
			if st.Lease.ClaimedBy != "" {
				n += ", leased"
			}
			next = append(next, n+")")
		}
		b := f.Budget
		rows = append(rows, fmt.Sprintf("| %d | %s | %s | %d %s | %s | %d / %d |",
			f.Priority, f.Feature, kindLabel(f), f.Phase, PhaseName(f),
			orDash(strings.Join(next, ", ")), b.Spent.Steps, b.Estimate.Steps))
	}
	if len(rows) == 0 {
		fmt.Fprintf(b, "Nothing in progress.\n")
		return
	}
	fmt.Fprintf(b, "| Pri | Feature | Kind | Phase | Next steps | Steps spent / est. |\n")
	fmt.Fprintf(b, "|---|---|---|---|---|---|\n")
	for _, r := range rows {
		fmt.Fprintf(b, "%s\n", r)
	}
}

func (s *State) hostSteps() []string {
	var out []string
	for _, f := range s.Features {
		if f.Status == "done" {
			continue
		}
		for _, st := range f.Steps {
			if st.Status == "pending" && strings.HasPrefix(st.Affinity, "host:") {
				host := strings.TrimPrefix(st.Affinity, "host:")
				out = append(out,
					fmt.Sprintf("**%s**: `%s` on %s", f.Feature, st.ID, host))
			}
		}
	}
	return out
}

func (s *State) writeBacklog(b *strings.Builder) {
	fmt.Fprintf(b, "\n## Backlog\n\n")
	var rows []string
	for _, f := range s.Features {
		if f.Status == "queued" {
			rows = append(rows, fmt.Sprintf("| %d | %s | %s | %d |",
				f.Priority, f.Feature, kindLabel(f), f.Budget.Estimate.Steps))
		}
	}
	if len(rows) == 0 {
		fmt.Fprintf(b, "Empty.\n")
		return
	}
	fmt.Fprintf(b, "| Pri | Feature | Kind | Est. steps |\n|---|---|---|---|\n")
	for _, r := range rows {
		fmt.Fprintf(b, "%s\n", r)
	}
}

func (s *State) recentlyDone(updated time.Time) []string {
	cutoff := updated.Add(-recentDays * 24 * time.Hour)
	var out []string
	for _, f := range s.Features {
		if f.Status != "done" || len(f.History) == 0 {
			continue
		}
		last := f.History[len(f.History)-1].At
		if last.Before(cutoff) {
			continue
		}
		ref := ""
		if f.PR != nil && f.PR.Number > 0 {
			ref = fmt.Sprintf(" #%d,", f.PR.Number)
		}
		day := last.UTC().Format("2006-01-02")
		out = append(out, fmt.Sprintf("%s:%s %s", f.Feature, ref, day))
	}
	return out
}

func kindLabel(f *Feature) string {
	if !f.IsProcess() {
		return "feature"
	}
	if len(f.Holds) == 0 {
		return "process"
	}
	return "process (holds " + strings.Join(f.Holds, ", ") + ")"
}

func orDash(s string) string {
	if s == "" {
		return "-"
	}
	return s
}
