package queue

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"time"
)

// SummaryFile is the generated overview at the root of the workflow branch.
const SummaryFile = "QUEUE.md"

// Summary renders the queue as Markdown: main's state, what needs the human
// first, then what is active, the machines (Workers), the relations, what waits on a host and the
// backlog, each in FLOW-05 order. Done items are left out (FLOW-13). It reads
// only the state, never the clock or git, so the same state always renders
// the same text.
func Summary(s *State) string {
	updated := s.updated()
	var b strings.Builder
	fmt.Fprintf(&b, "# Queue\n\nGenerated by `wf` from `queue/*.yaml`, `config.yaml`, "+
		"`areas.yaml` and `main.yaml`; do not edit. Updated %s.\n", stamp(updated))
	fmt.Fprintf(&b, "%s\n", s.mainLine())

	s.writeNeedsHuman(&b)
	s.writeActive(&b)
	s.writeWorkers(&b)
	s.writeRelations(&b)
	if hosts := s.hostSteps(); len(hosts) > 0 {
		section(&b, "Waiting on a host", hosts, "")
	}
	s.writeBacklog(&b)
	return b.String()
}

// WriteSummary writes Summary to QUEUE.md in the state's directory.
func (s *State) WriteSummary() error {
	return os.WriteFile(filepath.Join(s.Dir, SummaryFile), []byte(Summary(s)), 0o644)
}

func section(b *strings.Builder, title string, lines []string, empty string) {
	fmt.Fprintf(b, "\n## %s\n\n", title)
	if len(lines) == 0 {
		fmt.Fprintf(b, "%s\n", empty)
		return
	}
	for _, l := range lines {
		fmt.Fprintf(b, "- %s\n", l)
	}
}

// updated is the newest history event across the queue.
func (s *State) updated() time.Time {
	var t time.Time
	for _, f := range s.Features {
		for _, e := range f.History {
			if e.At.After(t) {
				t = e.At
			}
		}
	}
	return t
}

func stamp(t time.Time) string {
	if t.IsZero() {
		return "never"
	}
	return t.UTC().Format("2006-01-02 15:04 UTC")
}

// readySteps returns the feature's offered pending steps whose needs are all
// done.
func readySteps(f *Feature) []*Step {
	done := map[string]bool{}
	for _, st := range f.Steps {
		if st.Status == "done" {
			done[st.ID] = true
		}
	}
	var out []*Step
	for i := range f.Steps {
		st := &f.Steps[i]
		if st.Status == "pending" && Offered(f, st) && allDone(st.Needs, done) {
			out = append(out, st)
		}
	}
	return out
}

func humanStep(st *Step) string {
	switch {
	case strings.Contains(st.ID, "design-review"), strings.HasSuffix(st.ID, "1-design"):
		return "design review (`" + st.ID + "`, FLOW-19)"
	case strings.Contains(st.ID, "escalate"):
		return "escalation (`" + st.ID + "`)"
	}
	return "`" + st.ID + "`"
}

// hostSteps lists every pending host step, marking one whose phase the
// feature has not reached, so it shows before it is offered.
func (s *State) hostSteps() []string {
	var out []string
	for _, f := range s.Ordered() {
		if f.Status == "done" {
			continue
		}
		for i := range f.Steps {
			st := &f.Steps[i]
			if st.Status != "pending" || !strings.HasPrefix(st.Affinity, "host:") {
				continue
			}
			l := fmt.Sprintf("**%s**: `%s` on %s", f.Feature, st.ID,
				strings.TrimPrefix(st.Affinity, "host:"))
			if !Offered(f, st) {
				l += fmt.Sprintf(" (from phase %d)", st.Phase)
			}
			out = append(out, l)
		}
	}
	return out
}

func orDash(s string) string {
	if s == "" {
		return "-"
	}
	return s
}

// short abbreviates a commit id to 7 digits.
func short(sha string) string {
	if len(sha) > 7 {
		return sha[:7]
	}
	return sha
}

// count is n and the noun, with an s when n is not 1.
func count(n int, noun string) string {
	if n == 1 {
		return "1 " + noun
	}
	return fmt.Sprintf("%d %ss", n, noun)
}

// mainLine is the header's second line: main's CI as last recorded, whether
// GitHub requires an up-to-date branch on main, and the last comparison of
// the area map with main. What no session has recorded is said to be so,
// never read as green or as no difference (GLOBAL-10).
func (s *State) mainLine() string {
	m := s.Main
	if m == nil {
		m = &Main{}
	}
	ci := "`main`: CI not recorded."
	if m.CI != "" {
		ci = fmt.Sprintf("`main`: CI %s at `%s`.", m.CI, short(m.SHA))
	}
	const branch = "an up-to-date branch on `main`"
	up := map[string]string{
		"required":     "GitHub requires " + branch + " (FLOW-08).",
		"not-required": "GitHub does not require " + branch + " (FLOW-08).",
	}[m.UpToDate]
	if up == "" {
		up = "Whether GitHub requires " + branch + ": not recorded (FLOW-08)."
	}
	return ci + " " + up + " " + s.mapLine(m)
}

func (s *State) mapLine(m *Main) string {
	switch {
	case s.Areas == nil:
		return "Area map: none; each repository is one exclusive area (FLOW-05)."
	case m.Areas == nil:
		return "Area map: not checked against `main`."
	case m.Areas.Differences == 0:
		return fmt.Sprintf("Area map: no difference from `main` at `%s`.",
			short(m.Areas.SHA))
	}
	return fmt.Sprintf("Area map: %s from `main` at `%s` (wf areas -check).",
		count(m.Areas.Differences, "difference"), short(m.Areas.SHA))
}

// writeNeedsHuman is Needs Jeff: what stops the loop, the count of the items
// in progress that wait on the human beside the waiting limit (FLOW-05), the
// open pull requests in two lists (FLOW-08), the reviews, questions and
// escalations of the counted items, and then what the limit does not count.
func (s *State) writeNeedsHuman(b *strings.Builder) {
	fmt.Fprintf(b, "\n## Needs Jeff\n\n")
	for _, l := range s.alerts() {
		fmt.Fprintf(b, "%s\n\n", l)
	}
	fmt.Fprintf(b, "%s\n", s.waitingLine())
	ready := s.readyToMerge()
	if len(ready) > 0 {
		ready = append([]string{"One at a time: each merge puts every other open PR " +
			"behind `main`, and it needs a refresh before it can merge (FLOW-08).\n"},
			ready...)
	}
	subsection(b, "Ready to merge", ready)
	subsection(b, "After a refresh", s.afterRefresh())
	subsection(b, "Reviews, questions and escalations", s.reviews())
	subsection(b, "Not counted: queued, tracked, or not yet due", s.notCounted())
}

// subsection writes a ### list; a line that ends in a newline is a paragraph
// above it.
func subsection(b *strings.Builder, title string, lines []string) {
	fmt.Fprintf(b, "\n### %s\n\n", title)
	if len(lines) == 0 {
		fmt.Fprintf(b, "None.\n")
		return
	}
	for _, l := range lines {
		if strings.HasSuffix(l, "\n") {
			fmt.Fprintf(b, "%s\n", l)
			continue
		}
		fmt.Fprintf(b, "- %s\n", l)
	}
}

// alerts are the lines that open Needs Jeff: a red main, an area map that
// differs from main, and the holders over a limit.
func (s *State) alerts() []string {
	var out []string
	if m := s.Main; m != nil && m.CI == "red" {
		run := m.Run
		if run == "" {
			run = "no run recorded"
		}
		fix := "No follow-up is filed yet (FLOW-09)."
		if m.Followup != "" {
			fix = "Follow-up: **" + m.Followup + "**."
		}
		out = append(out, fmt.Sprintf("`main` is red at `%s` since `%s`: %s. %s No "+
			"open PR behind it can be made ready until it is green (FLOW-10).",
			short(m.SHA), short(m.RedSince), run, fix))
	}
	if m := s.Main; s.Areas != nil && m != nil && m.Areas != nil && m.Areas.Differences > 0 {
		out = append(out, fmt.Sprintf("The area map differs from `main` at `%s`: %s "+
			"(wf areas -check).", short(m.Areas.SHA),
			count(m.Areas.Differences, "line")))
	}
	for _, e := range s.validateLimits() {
		out = append(out, "Over a limit: "+e.Error())
	}
	return out
}

// waitKinds are the ways an item waits on the human, in the order the count
// names them.
var waitKinds = []string{"merge", "design review", "question", "escalation", "step",
	"runaway budget"}

// waitKind is what the counted item waits on the human for, the first that
// applies.
func (s *State) waitKind(f *Feature) string {
	if len(f.OpenBlocking()) > 0 {
		return "question"
	}
	if f.AtMerge() && f.hasPR() {
		return "merge"
	}
	for _, st := range readySteps(f) {
		if st.Affinity != "human" || st.Phase > f.Phase {
			continue
		}
		switch h := humanStep(st); {
		case strings.HasPrefix(h, "design review"):
			return "design review"
		case strings.HasPrefix(h, "escalation"):
			return "escalation"
		}
		return "step"
	}
	return "runaway budget"
}

// waitingLine is the count Needs Jeff opens with: the number Guard compares
// with the waiting limit, by what each item waits for (FLOW-05).
func (s *State) waitingLine() string {
	waiting, limit, past := s.pastWaitingLimit()
	if len(waiting) == 0 {
		return fmt.Sprintf("No item in progress waits on you (limit %d).", limit)
	}
	by := map[string]int{}
	for _, f := range waiting {
		by[s.waitKind(f)]++
	}
	var parts []string
	for _, k := range waitKinds {
		if by[k] > 0 {
			parts = append(parts, count(by[k], k))
		}
	}
	verb := "wait"
	if len(waiting) == 1 {
		verb = "waits"
	}
	l := fmt.Sprintf("%s in progress %s on you (limit %d): %s.",
		count(len(waiting), "item"), verb, limit, strings.Join(parts, ", "))
	if by["question"]+by["escalation"] == 0 {
		l += " No question or escalation."
	}
	if past {
		l += " No queued feature starts until one clears (FLOW-05)."
	}
	return l
}

// prLink is the item's pull request as a link, when the queue's repository is
// known; a tracked item's names its repository.
func (s *State) prLink(f *Feature, text string) string {
	if s.Tracked(f) {
		return fmt.Sprintf("%s#%d", s.Home(f), f.PR.Number)
	}
	if s.Home(f) == "" {
		return text
	}
	return fmt.Sprintf("[%s](https://github.com/%s/pull/%d)", text, s.Home(f), f.PR.Number)
}

// readyToMerge lists the open pull requests ready for the human's merge.
func (s *State) readyToMerge() []string {
	var out []string
	for _, f := range s.Ordered() {
		if f.ReadyToMerge() && !s.Tracked(f) {
			out = append(out, fmt.Sprintf("**%s**: %s, CI green", f.Feature,
				s.prLink(f, fmt.Sprintf("PR #%d", f.PR.Number))))
		}
	}
	return out
}

// afterRefresh lists the open pull requests that wait for a refresh, with
// the step's note, which says what moved main and which files overlap.
func (s *State) afterRefresh() []string {
	var out []string
	for _, f := range s.Ordered() {
		st := f.PendingRefresh()
		if f.Status != "in_progress" || !f.hasPR() || st == nil {
			continue
		}
		l := fmt.Sprintf("**%s**: %s: refresh pending (`%s`), then CI", f.Feature,
			s.prLink(f, fmt.Sprintf("PR #%d", f.PR.Number)), st.ID)
		if st.Note != "" {
			l += ". " + st.Note
		}
		if s.Main != nil && s.Main.CI == "red" && !s.fixesMain(f) {
			l += ". The refresh waits for `main` to be green (FLOW-10)"
		}
		out = append(out, l)
	}
	return out
}

// designLink is a link to the item's design on its branch.
func (s *State) designLink(f *Feature) string {
	if s.Config.Repository == "" || f.Branch == "" || f.Design == "" {
		return ""
	}
	return fmt.Sprintf(" · [design](https://github.com/%s/blob/%s/%s)",
		s.Config.Repository, f.Branch, f.Design)
}

// reviews lists, for the items the waiting limit counts, their questions,
// the human steps that are due, a pull request at its merge step that is not
// ready, and a spent budget; and every item sent back with its PR open.
func (s *State) reviews() []string {
	counted := map[*Feature]bool{}
	for _, f := range s.WaitsOnHuman() {
		counted[f] = true
	}
	var out []string
	for _, f := range s.Ordered() {
		add := func(format string, a ...any) {
			out = append(out, "**"+f.Feature+"**: "+fmt.Sprintf(format, a...))
		}
		if f.Status == "in_progress" && f.hasPR() && !s.Tracked(f) &&
			f.Phase < f.PublishPhase() {
			add("open PR #%d, returned to Implement: do not merge", f.PR.Number)
		}
		if counted[f] {
			s.waitLines(f, add)
		}
	}
	return out
}

// waitLines adds what the counted item waits on the human for.
func (s *State) waitLines(f *Feature, add func(format string, a ...any)) {
	for _, q := range f.OpenBlocking() {
		add("blocking question %s: %s (recommended: %s)", q.ID, q.Question,
			q.Recommended)
	}
	for _, st := range readySteps(f) {
		if st.Affinity == "human" && st.Phase <= f.Phase &&
			!strings.Contains(st.ID, "-answer-") {
			link := ""
			if strings.HasPrefix(humanStep(st), "design review") {
				link = s.designLink(f)
			}
			add("%s%s", humanStep(st), link)
		}
	}
	if f.AtMerge() && f.hasPR() && !f.ReadyToMerge() && f.PendingRefresh() == nil {
		add("%s at its merge step, CI %s: not ready (FLOW-08)",
			s.prLink(f, fmt.Sprintf("PR #%d", f.PR.Number)), f.PR.CI)
	}
	if s.Runaway(f) {
		bu := f.Budget
		add("runaway budget, %d of %d estimated steps spent (FLOW-13)",
			bu.Spent.Steps, bu.Estimate.Steps)
	}
}

// notCounted lists the human's lines the waiting limit does not count: a
// queued item's question or step, a tracked item's, and a human step of a phase its item
// has not reached, with that phase.
func (s *State) notCounted() []string {
	var out []string
	for _, f := range s.Ordered() {
		if f.Status == "done" {
			continue
		}
		if f.Status == "queued" {
			// A queued item on hold: the loop has put no work behind it.
			for _, q := range f.OpenBlocking() {
				out = append(out, fmt.Sprintf("**%s**: blocking question %s: %s "+
					"(recommended: %s)", f.Feature, q.ID, q.Question,
					q.Recommended))
			}
		}
		for _, st := range readySteps(f) {
			if st.Affinity != "human" || strings.Contains(st.ID, "-answer-") {
				continue
			}
			switch {
			case s.Tracked(f):
				what := "`" + st.ID + "`"
				if strings.HasSuffix(st.ID, "-merge") {
					what = "your merge (`" + st.ID + "`)"
				}
				where := s.Home(f)
				if f.hasPR() {
					where = s.prLink(f, "")
				}
				out = append(out, fmt.Sprintf("**%s** (tracked): %s, %s",
					f.Feature, where, what))
			case f.Status == "queued":
				out = append(out, "**"+f.Feature+"**: "+humanStep(st))
			case st.Phase > f.Phase:
				out = append(out, fmt.Sprintf("**%s**: %s (from phase %d)",
					f.Feature, humanStep(st), st.Phase))
			}
		}
	}
	return out
}

func (s *State) writeActive(b *strings.Builder) {
	fmt.Fprintf(b, "\n## Active\n\n")
	var rows []string
	for _, f := range s.Ordered() {
		if f.Status != "in_progress" {
			continue
		}
		var next []string
		for _, st := range readySteps(f) {
			n := fmt.Sprintf("%s (%s", st.ID, st.Affinity)
			if st.Lease.ClaimedBy != "" {
				n += ", leased to " + st.Lease.ClaimedBy
			}
			next = append(next, n+")")
		}
		bu := f.Budget
		rows = append(rows, fmt.Sprintf("| %d | %s | %s | %s | %s | %s | %d %s | %s | "+
			"%s | %s | %d / %d |", f.Priority, f.Feature, s.kindLabel(f),
			orDash(f.Lead), s.reposLabel(f), s.areasLabel(f), f.Phase, PhaseName(f),
			orDash(strings.Join(next, ", ")),
			s.waitsFor(f), s.prColumn(f), bu.Spent.Steps, bu.Estimate.Steps))
	}
	if len(rows) == 0 {
		fmt.Fprintf(b, "Nothing in progress.\n")
		return
	}
	fmt.Fprintf(b, "| Pri | Item | Kind | Lead | Repositories | Areas | Phase | "+
		"Next steps | Waits for | PR | Steps |\n")
	fmt.Fprintf(b, "|---|---|---|---|---|---|---|---|---|---|---|\n")
	for _, r := range rows {
		fmt.Fprintf(b, "%s\n", r)
	}
}

// writeWorkers is the Workers section, after Active: each machine of
// hosts.yaml with its host names, its last run from native/status/, the open
// items whose lead it serves and the pending steps leased to one of its
// sessions (FLOW-04, FLOW-09). The times are the files'; no clock is read, so
// an expired lease still shows until it is released or claimed again.
func (s *State) writeWorkers(b *strings.Builder) {
	if len(s.Machines) == 0 {
		return
	}
	fmt.Fprintf(b, "\n## Workers\n\n")
	fmt.Fprintf(b, "| Machine | Host names | Last run | Leads | Holds |\n")
	fmt.Fprintf(b, "|---|---|---|---|---|\n")
	for _, m := range s.Machines {
		var leads, holds []string
		serves := map[string]bool{}
		for _, h := range m.Hosts {
			serves["host:"+h] = true
		}
		for _, f := range s.Ordered() {
			if f.Status == "done" {
				continue
			}
			if serves[f.Lead] {
				leads = append(leads, f.Feature)
			}
			holds = append(holds, leasedOn(f, m.Name)...)
		}
		fmt.Fprintf(b, "| %s | %s | %s | %s | %s |\n", m.Name, strings.Join(m.Hosts, ", "),
			s.lastRun(m.Name), orDash(strings.Join(leads, ", ")),
			orDash(strings.Join(holds, ", ")))
	}
}

// leasedOn lists the item's pending steps leased to a session of the machine,
// with the lease's expiry.
func leasedOn(f *Feature, machine string) []string {
	var out []string
	for _, st := range f.Steps {
		if st.Status == "pending" && st.Lease.Expires != nil &&
			strings.HasPrefix(Session(st.Lease.ClaimedBy), machine+".") {
			out = append(out, fmt.Sprintf("%s/%s until %s", f.Feature, st.ID,
				st.Lease.Expires.UTC().Format("2006-01-02 15:04")))
		}
	}
	return out
}

// lastRun is the Workers table's Last run: native/status/<machine>.yaml's
// outcome, time, since when it has been so, and reason.
func (s *State) lastRun(machine string) string {
	for _, st := range s.Statuses {
		if st.Machine != machine {
			continue
		}
		const at = "2006-01-02 15:04"
		l := st.Outcome + ", " + st.LastRun.UTC().Format(at)
		if !st.Since.Equal(st.LastRun) {
			l += " (since " + st.Since.UTC().Format("2006-01-02") + ")"
		}
		return l + ": " + strings.ReplaceAll(st.Reason, "|", "\\|")
	}
	return "-"
}

// waitsFor is the Active table's Waits for: the human's merge, a refresh and
// then the merge, or the guard's reason for the item's next step.
func (s *State) waitsFor(f *Feature) string {
	if f.AtMerge() || (s.Tracked(f) && f.Phase == 2) {
		if f.PendingRefresh() != nil {
			return "a refresh, then your merge"
		}
		return "your merge"
	}
	for _, st := range readySteps(f) {
		if st.Phase > f.Phase {
			continue
		}
		return orDash(s.Guard(f, st, st.Affinity))
	}
	return "-"
}

func (s *State) prColumn(f *Feature) string {
	if !f.hasPR() {
		return "-"
	}
	if s.Tracked(f) {
		return s.prLink(f, "")
	}
	l := s.prLink(f, fmt.Sprintf("#%d", f.PR.Number))
	if f.PendingRefresh() != nil {
		l += " behind `main`"
	}
	return l
}

func (s *State) reposLabel(f *Feature) string {
	return orDash(strings.Join(s.ReposOf(f), ", "))
}

// areasLabel is the Areas column: undeclared, none, or the names, with a *
// after one the map lacks (the named fallback "area not in the map").
func (s *State) areasLabel(f *Feature) string {
	switch {
	case f.IsProcess() || s.Tracked(f):
		return "-"
	case f.Areas == nil:
		return "undeclared"
	case len(*f.Areas) == 0:
		return "none"
	}
	names := make([]string, len(*f.Areas))
	for i, a := range *f.Areas {
		names[i] = a
		if s.Areas == nil || !s.Areas.Has(a) {
			names[i] += "*"
		}
	}
	return strings.Join(names, ", ")
}

// writeRelations lists every pair of open features that is near or
// colliding, with the reason (FLOW-05).
func (s *State) writeRelations(b *strings.Builder) {
	fmt.Fprintf(b, "\n## Relations\n\nOpen features that are not disjoint. Process items "+
		"are outside the relations (FLOW-05).\n\n")
	var open []*Feature
	for _, f := range s.Listed(false) {
		if !f.IsProcess() {
			open = append(open, f)
		}
	}
	var rows []string
	for i, a := range open {
		for _, o := range open[i+1:] {
			if r := s.Relation(a, o); r.Kind == Colliding || r.Kind == Near {
				rows = append(rows, fmt.Sprintf("| %s, %s | %s | %s |", a.Feature,
					o.Feature, r.Kind, orDash(r.Reason)))
			}
		}
	}
	if len(rows) == 0 {
		fmt.Fprintf(b, "None: every pair is disjoint.\n")
		return
	}
	fmt.Fprintf(b, "| Items | Relation | Why |\n|---|---|---|\n")
	for _, r := range rows {
		fmt.Fprintf(b, "%s\n", r)
	}
}

func (s *State) writeBacklog(b *strings.Builder) {
	fmt.Fprintf(b, "\n## Backlog\n\n")
	var rows []string
	for _, f := range s.Ordered() {
		if f.Status == "queued" {
			rows = append(rows, fmt.Sprintf("| %d | %s | %s | %s | %s | %d |",
				f.Priority, f.Feature, s.kindLabel(f), s.reposLabel(f),
				s.areasLabel(f), f.Budget.Estimate.Steps))
		}
	}
	if len(rows) == 0 {
		fmt.Fprintf(b, "Empty.\n")
		return
	}
	if waiting, limit, past := s.pastWaitingLimit(); past {
		fmt.Fprintf(b, "No queued feature starts: %d items wait on you (limit %d). "+
			"Fixes, process items and security fixes you marked urgent still "+
			"start.\n\n",
			len(waiting), limit)
	}
	fmt.Fprintf(b, "| Pri | Item | Kind | Repositories | Areas | Est. steps |\n"+
		"|---|---|---|---|---|---|\n")
	for _, r := range rows {
		fmt.Fprintf(b, "%s\n", r)
	}
}

// kindLabel is the Kind column: a fix names the item it follows and an
// adoption the release it adopts (FLOW-05 class 3), a process item its holds,
// and a tracked item says so. A feature a human marked ends in ", urgent".
func (s *State) kindLabel(f *Feature) string {
	var k string
	switch {
	case f.IsProcess() && len(f.Holds) == 0:
		k = "process"
	case f.IsProcess():
		k = "process (holds " + strings.Join(f.Holds, ", ") + ")"
	case s.Tracked(f):
		k = "tracked"
	case f.Adopts != nil:
		k = fmt.Sprintf("adoption (%s %s)", f.Adopts.Consumable, f.Adopts.Version)
	case f.Follows != "":
		k = "fix (follows " + f.Follows + ")"
	default:
		k = "feature"
	}
	if f.marked() {
		k += ", urgent"
	}
	return k
}

func prRef(f *Feature) string {
	if !f.hasPR() {
		return "no PR recorded"
	}
	return fmt.Sprintf("PR #%d", f.PR.Number)
}
